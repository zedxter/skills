#!/usr/bin/env python3
"""Offline report: how the linter scores every corpus in test/data/prose/. No agents, no network.

    python3 -I corpus_report.py [--verbose]

Groups: human (should pass), slop (hand-written chat-model style, should fail), model (real model output
generated by generate_slop.py; articles and posts should mostly fail, docs often are fine), humanized (model
output told to avoid AI clichés; hard cases, reported only).
"""
import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "skills" / "human-writing" / "scripts"))
import lint_prose as lp  # noqa: E402

DATA = ROOT / "test" / "data" / "prose"


def group(path: Path) -> str:
    kind = path.parent.name
    if kind == "model" and path.stem.endswith("-humanized"):
        return "humanized"
    return kind


def main() -> int:
    verbose = "--verbose" in sys.argv
    table: dict[tuple[str, str], list] = defaultdict(list)
    for path in sorted(DATA.glob("*/*.md")):
        if path.name == "README.md" or path.parent.name == "seeded":
            continue
        genre = path.name.split("-")[0]
        r = lp.lint(path.read_text(encoding="utf-8"), lp.Settings(genre=genre))
        failed = r["score"] < lp.DEFAULT_THRESHOLD or r["counts"]["error"] > 0
        table[(group(path), genre)].append((path.name, r["score"], failed))
    print(f"{'group':<10} {'genre':<8} {'fail':>9}  scores")
    for (g, genre), rows in sorted(table.items()):
        fails = sum(f for _, _, f in rows)
        print(f"{g:<10} {genre:<8} {fails:>3}/{len(rows):<5}  " + " ".join(str(s) for _, s, _ in rows))
        if verbose:
            for name, s, f in rows:
                print(f"    {'FAIL' if f else 'pass'} {s:>3} {name}")
    print(json.dumps({f"{g}/{genre}": f"{sum(f for _, _, f in rows)}/{len(rows)}" for (g, genre), rows in sorted(table.items())}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
